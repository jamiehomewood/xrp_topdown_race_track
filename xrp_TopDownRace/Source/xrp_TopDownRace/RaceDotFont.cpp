bool RaceDotFont::IsLit(TCHAR Character, int32 X, int32 Y)
{
	if (X < 0 || X >= GlyphWidth || Y < 0 || Y >= GlyphHeight)
	{
		return false;
	}
	const FGlyph* Glyph = FindGlyph(Character);
	return Glyph && Glyph->Rows[Y][X] == '#';
}

int32 RaceDotFont::TextWidth(const FString& Text, int32 Scale)
{
	return Text.Len() > 0 ? (Text.Len() * Advance - 1) * Scale : 0;
}
