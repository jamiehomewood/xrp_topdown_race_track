	const FGlyph* FindGlyph(TCHAR Character)
	{
		static TMap<TCHAR, const FGlyph*> Lookup;
		if (Lookup.Num() == 0)
		{
			for (const FGlyph& Glyph : Glyphs)
			{
				Lookup.Add(Glyph.Character, &Glyph);
			}
		}
		const FGlyph* const* Found = Lookup.Find(FChar::ToUpper(Character));
		return Found ? *Found : nullptr;
	}
